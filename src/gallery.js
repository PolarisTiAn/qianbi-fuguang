function loadOfflineModel() {
  // A classic script can load beside index.html under file://, where fetch
  // cannot read a neighbouring GLB. Generated by build.mjs from the same asset.
  if (!offlineModelPromise) offlineModelPromise = new Promise((resolve, reject) => {
    const script = document.createElement('script');
    script.src = 'assets/cave61/interior-model.offline.js?v=20261029-embed';
    script.onload = () => {
      const encoded = window.__qianbiModelBase64;
      delete window.__qianbiModelBase64;
      script.remove();
      if (!encoded) { offlineModelPromise = null; reject(new Error('offline-model-empty')); return; }
      try {
        const bytes = Uint8Array.from(atob(encoded), c => c.charCodeAt(0));
        resolve(bytes.buffer);
      } catch (error) { offlineModelPromise = null; reject(error); }
    };
    script.onerror = () => { script.remove(); offlineModelPromise = null; reject(new Error('offline-model-load')); };
    document.head.append(script);
  });
  return offlineModelPromise;
}
