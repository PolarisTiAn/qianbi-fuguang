  async loadRefinedModel() {
    if (this.blenderRoot) return true;
    const loader = new GLTFLoader();
    const gltf = location.protocol === 'file:'
      ? await loader.parseAsync(await loadOfflineModel(), '')
      : await new Promise((resolve, reject) => loader.load(
      refinedModelURL,
      resolve,
      progress => {
        if (progress.total) {
          const percent = Math.round(progress.loaded / progress.total * 100);
          el('gallery-entry-message').textContent = `正在载入洞窟精修模型 ${percent}%…`;
        }
      },
      reject
    ));
    const root = gltf.scene;
    root.name = 'Mogao-061-Blender-interior-refined';
    root.userData = {
      source: refinedModelURL,
      accuracy: '公开照片引导的 Blender 精修估算，非测绘或扫描复原'
    };
    this.refinedCutawayMeshes = [];
    root.updateMatrixWorld(true);
    root.traverse(object => {
      if (!object.isMesh) return;
      object.castShadow = true;
      object.receiveShadow = true;
      object.frustumCulled = true;
      const materials = Array.isArray(object.material) ? object.material : [object.material];
      materials.forEach(material => {
        for (const value of Object.values(material)) {
          if (value?.isTexture) {
            this.textures.add(value);
            value.anisotropy = Math.min(4, this.renderer.capabilities.getMaxAnisotropy());
          }
        }
        // glTF does not carry Three.js polygon offsets. Restore them for
        // painted skins coincident with the underlying plaster surface.
        if (/^roof.*official-paint|^passage.*official-mural/.test(object.name)) {
          material.polygonOffset = true;
          material.polygonOffsetFactor = -2;
          material.polygonOffsetUnits = -2;
          object.castShadow = false;
        }
      });
      const name = object.name;
      const passageFloor = name.startsWith('main-floor-individual-slab-grid') &&
        new THREE.Box3().setFromObject(object).getCenter(new THREE.Vector3()).z > 6.4;
      if (/^(roof|central-painted-caisson|north-|east-|entrance-|door-|passage|甬道|主室北侧_|主室东侧)/.test(name) ||
        name.includes('窟顶结构边线') || passageFloor) this.refinedCutawayMeshes.push(object);
    });
    const wall = root.getObjectByName('west-wall-source-image');
    if (!wall) throw new Error('refined-model-wall-missing');
    // Reuse the existing wall shader so the published color-process controls
    // still work on the Blender geometry.
    wall.material.dispose();
    wall.material = this.wallMaterial;
    this.scene.add(root);
    this.blenderRoot = root;
    this.blenderWall = wall;
    this.proceduralRoot.visible = false;
    this.modelRoot = root;
    this.wallMesh = wall;
    frame.dataset.model = 'blender-refined';
    el('gallery-frame').querySelector('.gallery-live').textContent = '洞窟精修模型';
    this.scene.updateMatrixWorld(true);
    this.renderer.shadowMap.needsUpdate = true;
    this.render();
    return true;
  }
